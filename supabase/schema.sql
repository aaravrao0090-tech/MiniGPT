-- MiniGPT shared knowledge table
-- Run this in the Supabase SQL Editor.
create table if not exists public.minigpt_memories (
  id bigint generated by default as identity primary key,
  content text not null check (char_length(content) between 10 and 5000),
  created_at timestamptz not null default now()
);

alter table public.minigpt_memories enable row level security;

drop policy if exists "Anyone can read shared MiniGPT memories" on public.minigpt_memories;
create policy "Anyone can read shared MiniGPT memories"
on public.minigpt_memories for select to anon, authenticated using (true);

-- No public insert/update/delete policies. Writes must go through the Edge Function.
grant select on public.minigpt_memories to anon, authenticated;
